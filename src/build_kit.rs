//! The pinned build environment: the official image and the fixed package closure.
//!
//! Before a build the runner ensures this official image is on the host, stages the Debian
//! packages of this manifest, and only then starts the build container. Image and manifest
//! are pinned together: they belong to one snapshot.debian.org timestamp (the libc6 in the
//! image is exactly the version `libc6-dev` asks for).

use std::sync::OnceLock;

/// The official image, referenced by its index fingerprint.
pub const BUILD_ENV_IMAGE_REF: &str =
    "debian@sha256:7c7b2c966bc9ee8cedfeef67e0e279108992c77681fa595db4a9d65c06ccc587";

/// The amd64 image ID of that image as the classic image store reports it
/// (measured on the target host).
pub const BUILD_ENV_IMAGE_ID: &str =
    "sha256:d4c45f66efc59f89b0597d343a9bd72808493c0eacecde5285961743252cee23";

/// The index digest inside [`BUILD_ENV_IMAGE_REF`]. A containerd-backed image
/// store reports this as the local image ID where a classic store reports the
/// per-platform image ID; both name the same pinned amd64 image.
pub const BUILD_ENV_IMAGE_INDEX_ID: &str =
    "sha256:7c7b2c966bc9ee8cedfeef67e0e279108992c77681fa595db4a9d65c06ccc587";

/// The architecture of the build environment: the target is amd64.
pub const BUILD_ENV_PLATFORM: &str = "linux/amd64";

/// The frozen snapshot.debian.org timestamp the closure belongs to.
pub const BUILD_ENV_SNAPSHOT: &str = "20261005T000000Z";

/// The manifest itself, generated by `tools/build-kit.sh gen`.
pub const MANIFEST: &str = include_str!("build_kit/packages.tsv");

/// One manifest row: one pinned Debian package.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KitPackage {
    pub sha256: String,
    pub bytes: u64,
    /// URL basename, including percent escapes used by Debian epoch versions.
    pub filename: String,
    pub package: String,
    pub version: String,
    pub url: String,
}

/// The embedded manifest, parsed once. A parse error is returned to the caller,
/// which reports it as a build failure instead of guessing.
pub fn packages() -> Result<&'static [KitPackage], String> {
    static PARSED: OnceLock<Result<Vec<KitPackage>, String>> = OnceLock::new();
    match PARSED.get_or_init(|| parse_manifest(MANIFEST)) {
        Ok(packages) => Ok(packages.as_slice()),
        Err(error) => Err(error.clone()),
    }
}

/// One comment header line of the manifest (`image`, `snapshot`,...), used to
/// cross-check the tool's constants against the program's.
pub fn manifest_header(key: &str) -> Option<&'static str> {
    MANIFEST.lines().find_map(|line| {
        let rest = line.strip_prefix("# ")?;
        let (k, v) = rest.split_once(": ")?;
        (k == key).then_some(v)
    })
}

/// Parse manifest text: comments and blank lines are skipped, a data row must
/// carry six tab-separated fields that all pass their shape checks, and every
/// file name must be unique; anything else is refused as a whole.
pub fn parse_manifest(text: &str) -> Result<Vec<KitPackage>, String> {
    let mut out: Vec<KitPackage> = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let number = index + 1;
        let fields: Vec<&str> = line.split('\t').collect();
        let [sha256, bytes, filename, package, version, url] = fields[..] else {
            return Err(format!("line {number}: expected six tab-separated fields"));
        };
        if !is_hex(sha256, 64) {
            return Err(format!("line {number}: bad SHA256"));
        }
        let Ok(bytes) = bytes.parse::<u64>() else {
            return Err(format!("line {number}: bad byte count"));
        };
        if bytes == 0 {
            return Err(format!("line {number}: bad byte count"));
        }
        if !filename_ok(filename) {
            return Err(format!("line {number}: bad file name"));
        }
        if !package_ok(package) || !filename.starts_with(&format!("{package}_")) {
            return Err(format!("line {number}: bad package name"));
        }
        if !version_ok(version) {
            return Err(format!("line {number}: bad version"));
        }
        if !url_ok(url, filename) {
            return Err(format!("line {number}: bad snapshot address"));
        }
        if out.iter().any(|p| p.filename == filename) {
            return Err(format!("line {number}: duplicate file name"));
        }
        out.push(KitPackage {
            sha256: sha256.to_string(),
            bytes,
            filename: filename.to_string(),
            package: package.to_string(),
            version: version.to_string(),
            url: url.to_string(),
        });
    }
    if out.is_empty() {
        return Err("the manifest has no package row".into());
    }
    Ok(out)
}

fn is_hex(s: &str, len: usize) -> bool {
    s.len() == len
        && s.bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// The closed shape of a local image ID: `sha256:` plus 64 lowercase hex digits.
pub fn image_id_ok(s: &str) -> bool {
    matches!(s.strip_prefix("sha256:"), Some(hex) if is_hex(hex, 64))
}

/// A download file name: the last URL segment, possibly percent-escaped (an
/// epoch version is written `%3a`).
fn filename_ok(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 200
        && s != "."
        && s != ".."
        && s.bytes().all(|b| {
            b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'+' | b'-' | b'~' | b'%' | b':')
        })
}

/// Debian package names use lowercase letters, digits, plus, minus and dot.
fn package_ok(s: &str) -> bool {
    let mut bytes = s.bytes();
    match bytes.next() {
        Some(b) if b.is_ascii_lowercase() || b.is_ascii_digit() => {}
        _ => return false,
    }
    s.len() <= 100
        && s.bytes().all(|b| {
            b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'+' | b'.' | b'-')
        })
}

/// The closed shape of a Debian version: starts with a digit and allows the
/// epoch, the revision and `~`/`+`.
fn version_ok(s: &str) -> bool {
    let mut bytes = s.bytes();
    match bytes.next() {
        Some(b) if b.is_ascii_digit() => {}
        _ => return false,
    }
    s.len() <= 100
        && s.bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'+' | b'-' | b'~' | b':'))
}

/// The address must be the pool path of this snapshot timestamp in one of the
/// two archives, and its last segment must be the recorded file name.
fn url_ok(url: &str, filename: &str) -> bool {
    const BASES: [&str; 2] = [
        "https://snapshot.debian.org/archive/debian/",
        "https://snapshot.debian.org/archive/debian-security/",
    ];
    let Some(rest) = BASES.iter().find_map(|base| url.strip_prefix(base)) else {
        return false;
    };
    let Some(rest) = rest.strip_prefix(BUILD_ENV_SNAPSHOT) else {
        return false;
    };
    let Some(pool) = rest.strip_prefix("/pool/") else {
        return false;
    };
    if pool.is_empty() || pool.contains("..") {
        return false;
    }
    if !pool.bytes().all(|b| {
        b.is_ascii_alphanumeric()
            || matches!(b, b'.' | b'_' | b'+' | b'-' | b'~' | b'%' | b':' | b'/')
    }) {
        return false;
    }
    url.len() <= 500 && url.ends_with(&format!("/{filename}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_embedded_manifest_matches_the_pinned_environment() {
        // The manifest is generated: its header must agree with the constants
        // here, otherwise tool and program would not pin the same image and
        // timestamp.
        assert_eq!(manifest_header("image"), Some(BUILD_ENV_IMAGE_REF));
        assert_eq!(manifest_header("image_id"), Some(BUILD_ENV_IMAGE_ID));
        assert_eq!(manifest_header("snapshot"), Some(BUILD_ENV_SNAPSHOT));
        assert_eq!(
            manifest_header("top_packages"),
            Some("gcc-12 binutils make libc6-dev kmod squashfs-tools libelf-dev patch xz-utils")
        );
        assert_eq!(
            manifest_header("columns"),
            Some("sha256, bytes, filename, package, version, url (tab-separated)")
        );
        let packages = packages().expect("the embedded manifest parses");
        assert_eq!(packages.len(), 49);
        assert_eq!(manifest_header("packages"), Some("49"));
        // Every name appears once and every address sits under the pinned
        // timestamp.
        let mut names: Vec<&str> = packages.iter().map(|p| p.filename.as_str()).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), packages.len());
        assert!(packages
            .iter()
            .all(|p| p.url.contains(BUILD_ENV_SNAPSHOT) && p.url.ends_with(&p.filename)));
        // The closure must carry the compiler and packaging tools the build
        // script uses.
        for wanted in [
            "gcc-12",
            "binutils",
            "make",
            "libc6-dev",
            "kmod",
            "squashfs-tools",
            "libelf-dev",
            "patch",
            "xz-utils",
        ] {
            assert!(
                packages.iter().any(|p| p.package == wanted),
                "the closure is missing {wanted}"
            );
        }
    }

    #[test]
    fn the_manifest_parser_refuses_malformed_rows() {
        let good = "aa".repeat(32);
        let row = |sha: &str, bytes: &str, rest: &str| format!("{sha}\t{bytes}\t{rest}\n");
        let url = "https://snapshot.debian.org/archive/debian/20261005T000000Z/pool/main/g/gcc-12/gcc-12_12.2.0-14+deb12u1_amd64.deb";
        let head = "gcc-12_12.2.0-14+deb12u1_amd64.deb\tgcc-12\t12.2.0-14+deb12u1";
        assert_eq!(
            parse_manifest(&row(&good, "42", &format!("{head}\t{url}")))
                .unwrap()
                .len(),
            1
        );
        // Comment and blank lines take no part.
        assert!(parse_manifest("# x: y\n\n").is_err());
        // One counterexample per field.
        assert!(parse_manifest(&row("AA", "42", &format!("{head}\t{url}"))).is_err());
        assert!(parse_manifest(&row(&good, "0", &format!("{head}\t{url}"))).is_err());
        assert!(parse_manifest(&row(&good, "42", &format!("../x\tgcc-12\t1\t{url}"))).is_err());
        assert!(parse_manifest(&row(
            &good,
            "42",
            &format!("other_1_amd64.deb\tgcc-12\t1\t{url}")
        ))
        .is_err());
        assert!(parse_manifest(&row(&good, "42", &format!("{head}\t{url}x"))).is_err());
        assert!(parse_manifest(&row(
            &good,
            "42",
            "gcc-12_1_amd64.deb\tgcc-12\t1\thttps://example.com/pool/main/g/gcc-12/gcc-12_1_amd64.deb"
        ))
        .is_err());
        // A missing field and a repeated file name are refused.
        assert!(parse_manifest(&format!("{good}\t42\t{head}\n")).is_err());
        assert!(parse_manifest(&format!(
            "{}\n{}",
            row(&good, "42", &format!("{head}\t{url}")),
            row(&good, "42", &format!("{head}\t{url}"))
        ))
        .is_err());
    }
}
